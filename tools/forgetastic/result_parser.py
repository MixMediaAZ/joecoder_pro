# tools/forgetastic/result_parser.py (Parse Test Results - JUnit, Coverage)

from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Optional

from .common import get_logger

log = get_logger("result_parser")


@dataclass(frozen=True)
class TestMetrics:
    """Parsed test metrics from JUnit XML."""
    total_tests: int
    passed: int
    failed: int
    skipped: int
    errors: int
    execution_time_seconds: float
    test_cases: list[dict[str, Any]]  # Individual test details


@dataclass(frozen=True)
class CoverageMetrics:
    """Parsed coverage metrics from coverage.xml."""
    line_rate: float  # 0.0-1.0
    branch_rate: float  # 0.0-1.0
    lines_valid: int
    lines_covered: int
    branches_valid: int
    branches_covered: int
    packages: list[dict[str, Any]]  # Per-package coverage


def parse_junit_xml(junit_xml_path: Path) -> Optional[TestMetrics]:
    """
    Parse JUnit XML and extract test metrics.

    Supports standard JUnit format generated by pytest, maven, gradle, etc.

    Returns:
        TestMetrics with parsed results, or None if parsing fails
    """
    if not junit_xml_path.exists():
        log.error(f"JUnit XML not found: {junit_xml_path}")
        return None

    try:
        tree = ET.parse(junit_xml_path)
        root = tree.getroot()
    except ET.ParseError as e:
        log.error(f"Failed to parse JUnit XML: {e}")
        return None

    # Extract summary from testsuite or testsuites root
    if root.tag == "testsuites":
        # Multiple test suites (e.g., pytest with multiple test files)
        total_tests = int(root.get("tests", 0))
        failures = int(root.get("failures", 0))
        skipped = int(root.get("skipped", 0))
        errors = int(root.get("errors", 0))
        time_seconds = float(root.get("time", 0))
    elif root.tag == "testsuite":
        # Single test suite
        total_tests = int(root.get("tests", 0))
        failures = int(root.get("failures", 0))
        skipped = int(root.get("skipped", 0))
        errors = int(root.get("errors", 0))
        time_seconds = float(root.get("time", 0))
    else:
        log.error(f"Unexpected root element: {root.tag}")
        return None

    passed = total_tests - failures - skipped - errors

    # Extract individual test cases
    test_cases: list[dict[str, Any]] = []
    for testcase in root.findall(".//testcase"):
        tc = {
            "name": testcase.get("name", "unknown"),
            "classname": testcase.get("classname", "unknown"),
            "time": float(testcase.get("time", 0)),
            "status": "PASS",
            "message": None,
        }

        # Check for failure, error, or skip
        failure = testcase.find("failure")
        if failure is not None:
            tc["status"] = "FAIL"
            tc["message"] = failure.get("message", "")

        error = testcase.find("error")
        if error is not None:
            tc["status"] = "ERROR"
            tc["message"] = error.get("message", "")

        skip = testcase.find("skipped")
        if skip is not None:
            tc["status"] = "SKIP"
            tc["message"] = skip.get("message", "")

        test_cases.append(tc)

    return TestMetrics(
        total_tests=total_tests,
        passed=passed,
        failed=failures,
        skipped=skipped,
        errors=errors,
        execution_time_seconds=time_seconds,
        test_cases=test_cases,
    )


def parse_coverage_xml(coverage_xml_path: Path) -> Optional[CoverageMetrics]:
    """
    Parse coverage.xml (Cobertura format) and extract coverage metrics.

    Supports cobertura-generated coverage.xml from pytest-cov, jacoco, etc.

    Returns:
        CoverageMetrics with parsed results, or None if parsing fails
    """
    if not coverage_xml_path.exists():
        log.error(f"Coverage XML not found: {coverage_xml_path}")
        return None

    try:
        tree = ET.parse(coverage_xml_path)
        root = tree.getroot()
    except ET.ParseError as e:
        log.error(f"Failed to parse coverage XML: {e}")
        return None

    if root.tag != "coverage":
        log.error(f"Unexpected root element: {root.tag}, expected 'coverage'")
        return None

    # Extract overall metrics
    line_rate = float(root.get("line-rate", 0))
    branch_rate = float(root.get("branch-rate", 0))
    lines_valid = int(root.get("lines-valid", 0))
    lines_covered = int(root.get("lines-covered", 0))
    branches_valid = int(root.get("branches-valid", 0))
    branches_covered = int(root.get("branches-covered", 0))

    # Extract per-package coverage
    packages: list[dict[str, Any]] = []
    for package in root.findall("packages/package"):
        pkg = {
            "name": package.get("name", "unknown"),
            "line_rate": float(package.get("line-rate", 0)),
            "branch_rate": float(package.get("branch-rate", 0)),
        }
        packages.append(pkg)

    return CoverageMetrics(
        line_rate=line_rate,
        branch_rate=branch_rate,
        lines_valid=lines_valid,
        lines_covered=lines_covered,
        branches_valid=branches_valid,
        branches_covered=branches_covered,
        packages=packages,
    )


def metrics_to_dict(metrics: TestMetrics) -> dict[str, Any]:
    """Convert TestMetrics to dict for JSON serialization."""
    return {
        "total_tests": metrics.total_tests,
        "passed": metrics.passed,
        "failed": metrics.failed,
        "skipped": metrics.skipped,
        "errors": metrics.errors,
        "execution_time_seconds": metrics.execution_time_seconds,
        "pass_rate": metrics.passed / metrics.total_tests if metrics.total_tests > 0 else 0.0,
        "test_cases": metrics.test_cases,
    }


def coverage_to_dict(coverage: CoverageMetrics) -> dict[str, Any]:
    """Convert CoverageMetrics to dict for JSON serialization."""
    return {
        "line_rate": coverage.line_rate,
        "branch_rate": coverage.branch_rate,
        "line_coverage_percent": coverage.line_rate * 100,
        "branch_coverage_percent": coverage.branch_rate * 100,
        "lines_valid": coverage.lines_valid,
        "lines_covered": coverage.lines_covered,
        "branches_valid": coverage.branches_valid,
        "branches_covered": coverage.branches_covered,
        "packages": coverage.packages,
    }
